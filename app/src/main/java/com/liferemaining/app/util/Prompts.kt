package com.liferemaining.app.util

/**
 * 今日行动候选。全部本地内置，不需要网络，也不制造焦虑。
 * 文案按「今天能做完」的小动作设计。
 */
object ActionPrompts {
    val all: List<String> = listOf(
        "给重要的人打一个电话。",
        "为自己的长期目标推进一步。",
        "留出一点时间给真正喜欢的事情。",
        "今天结束前，记录一件值得记住的事。",
        "把一直拖着的那件小事做完。",
        "走一段路，不看手机。",
        "对一个人说出你一直想说的谢谢。",
        "整理一处你每天都会看到的空间。",
        "翻开那本停了很久的书。",
        "早一点睡，把明天还给自己。",
        "删掉一个不再需要的计划。",
        "认真吃一顿饭，不赶时间。",
        "把今天的感受写下一句话。",
        "给自己留半小时，不做任何安排。",
        "问一个朋友最近过得怎么样，并听完。",
        "做完一件拖了很久的家务。",
        "把手机放在另一个房间，专注 25 分钟。",
        "想一个五年后仍然重要的问题。",
        "拒绝一件并不重要的事。",
        "把今天的照片留一张，写一句说明。"
    )

    fun promptAt(seed: Int): String = all[Math.floorMod(seed, all.size)]

    /** 与日期和手动换句次数相关，保证同一天刷新不会乱跳。 */
    fun promptFor(dayOfYear: Int, shuffle: Int): String = promptAt(dayOfYear * 7 + shuffle * 13)
}
